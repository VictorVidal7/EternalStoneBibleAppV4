/**
 * 📖 generate-verse-counts — one-time (re-run-on-demand) generator that
 * derives "how many verses does book X chapter Y have" from the bundled
 * RVR1960 text already shipped in `assets/bible-seed.db`, and writes the
 * answer out as a small static TS module
 * (`src/constants/bible-verse-counts.ts`).
 *
 * Why this exists: `parseReference` (src/lib/references/parseReference.ts)
 * validates a citation's CHAPTER against `BibleBook.chapters`, but had no
 * way to validate the VERSE number against that chapter's actual size, so
 * out-of-range citations like "Gá 6:19" (Gálatas 6 only has 18 verses)
 * resolved as tappable dead-end links. Rather than statically importing the
 * full ~31k-row `bible-data-rvr1960.ts` (lazily code-split on purpose — see
 * data-loader.ts) into the always-loaded reference parser, this script
 * pre-computes the answer ONCE into a tiny (66 books × ≤150 chapters)
 * lookup table that's cheap to bundle everywhere.
 *
 * Re-run with: `node scripts/generate-verse-counts.js`
 * (only needed if a translation-pack/versification change ever alters
 * chapter/verse boundaries for the bundled RVR1960 text — it doesn't, since
 * RVR1960 versification is fixed, but this keeps the table honest either way).
 *
 * Para la gloria de Dios Todopoderoso ✨
 */

const fs = require('fs');
const path = require('path');
const {DatabaseSync} = require('node:sqlite');

const ROOT = path.resolve(__dirname, '..');
const SEED = path.join(ROOT, 'assets', 'bible-seed.db');
const OUT = path.join(ROOT, 'src', 'constants', 'bible-verse-counts.ts');

const db = new DatabaseSync(SEED, {readOnly: true});
const rows = db
  .prepare(
    `SELECT book_id, chapter, MAX(verse) as maxVerse
     FROM verses
     WHERE version = 'RVR1960'
     GROUP BY book_id, chapter
     ORDER BY book_id, chapter`,
  )
  .all();
db.close();

if (rows.length === 0) {
  throw new Error('generate-verse-counts: no rows read from bible-seed.db');
}

/** @type {Record<number, number[]>} book_id -> [verses in ch1, ch2, ...] */
const perBook = {};
let maxBookId = 0;
for (const row of rows) {
  const bookId = Number(row.book_id);
  const chapter = Number(row.chapter);
  const maxVerse = Number(row.maxVerse);
  if (!perBook[bookId]) perBook[bookId] = [];
  perBook[bookId][chapter - 1] = maxVerse;
  if (bookId > maxBookId) maxBookId = bookId;
}

const table = [];
for (let id = 1; id <= maxBookId; id++) {
  const chapters = perBook[id];
  if (!chapters) {
    throw new Error(`generate-verse-counts: no data for book_id ${id}`);
  }
  for (let i = 0; i < chapters.length; i++) {
    if (!Number.isInteger(chapters[i]) || chapters[i] < 1) {
      throw new Error(
        `generate-verse-counts: missing/invalid verse count for book_id ${id} chapter ${
          i + 1
        }`,
      );
    }
  }
  table.push(chapters);
}

const header = `/**
 * Auto-generated by scripts/generate-verse-counts.js — DO NOT EDIT BY HAND.
 *
 * Verse counts per chapter for the bundled RVR1960 text, derived from
 * \`assets/bible-seed.db\`. Indexed \`[bookId - 1][chapter - 1]\` (BibleBook.id
 * is 1-based, matching \`verses.book_id\` in the seed DB — see BIBLE_BOOKS in
 * src/constants/bible.ts, whose \`chapters\` count per book was cross-checked
 * against this same source and matches exactly).
 *
 * Regenerate with: node scripts/generate-verse-counts.js
 */

/** \`VERSE_COUNTS_BY_BOOK[bookId - 1][chapter - 1]\` = number of verses in
 *  that chapter, or \`undefined\` if \`chapter\` is out of range for the book. */
export const VERSE_COUNTS_BY_BOOK: readonly (readonly number[])[] = ${JSON.stringify(
  table,
)};

/** Number of verses in \`book\` \`chapter\`, or \`undefined\` if the book id or
 *  chapter number is out of range. */
export function getChapterVerseCount(
  bookId: number,
  chapter: number,
): number | undefined {
  return VERSE_COUNTS_BY_BOOK[bookId - 1]?.[chapter - 1];
}
`;

fs.writeFileSync(OUT, header, 'utf8');
console.log(
  `Wrote ${OUT} (${table.length} books, ${rows.length} chapter entries).`,
);
